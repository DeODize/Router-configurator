#!/bin/bash

# Функция для вывода справки по использованию
usage() {
    echo "Использование: $0 <файл> <искомая_строка> <строка_замены>"
    echo "Пример: $0 config.txt 'old_value' 'new_value'"
    exit 1
}

# Проверка: передано ли ровно 3 аргумента
if [ "$#" -ne 3 ]; then
    echo "Ошибка: неверное количество аргументов."
    usage
fi

FILE=$1
SEARCH=$2
REPLACE=$3

# Проверка: существует ли указанный файл
if [ ! -f "$FILE" ]; then
    echo "Ошибка: Файл '$FILE' не найден или не является обычным файлом."
    exit 1
fi

# Создаем резервную копию файла перед изменением (на случай ошибки)
cp "$FILE" "${FILE}.bak"

# Выполняем замену
# Мы используем символ '@' как разделитель вместо стандартного '/',
# чтобы можно было спокойно искать и заменять пути (например, /var/www).
# Флаг 'g' означает замену всех вхождений в строке, а не только первого.
sed -i "s@$SEARCH@$REPLACE@" "$FILE"

echo "Замена успешно выполнена в файле '$FILE'."
echo "Резервная копия сохранена в '${FILE}.bak'."
